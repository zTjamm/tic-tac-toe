/**
 * Рейтинг матча.
 *
 * Формула Эло с асимметрией: за победу даётся больше, чем теряется за
 * поражение - в матче «до 5 очков» атакующий играет на победу чаще, чем
 * защитник, и выигрыш должен быть чуть выгоднее.
 *
 * Коэффициенты подобраны так, чтобы при равных рейтингах результат был
 * ровно как раньше: +2 за победу и -1 за поражение.
 *
 * Система намеренно НЕ нулевая: при равных рейтингах за матч суммарно
 * добавляется +1 очко (как в прежней плоской формуле), а при сильном
 * разрыве фаворит получает +1, а андердог теряет -2, то есть сумма
 * уходит вниз. Это цена за асимметрию "победа выгоднее поражения" -
 * она же была и раньше. Проверки в test-rating.js фиксируют оба края.
 */

const SCALE = 400;          // как в классическом Эло: разница в 400 - это 10:1
const GAIN_SCALE = 4;       // победа равных: round(4 * 0.5) = +2
const LOSS_SCALE = 2;       // поражение равных: round(2 * 0.5) = -1
const MIN_DELTA = 1;        // результат всегда что-то меняет, иначе -0 и "ничего не произошло"

/** Ожидаемая доля побед сильнейшего: 0.5 при равных, 0.9 при +200. */
function expectedShare(winnerRating, loserRating) {
    return 1 / (1 + Math.pow(10, (loserRating - winnerRating) / SCALE));
}

/**
 * Изменения рейтинга обоих участников. Считаются от их рейтингов ДО матча
 * и всегда симметричны по знаку: выигравший растёт, проигравший падает.
 *
 * @returns {{win: number, loss: number}} дельты, loss <= 0
 */
function matchDeltas(winnerRating, loserRating) {
    const e = expectedShare(winnerRating, loserRating);
    return {
        win: Math.max(MIN_DELTA, Math.round(GAIN_SCALE * (1 - e))),
        loss: -Math.max(MIN_DELTA, Math.round(LOSS_SCALE * e))
    };
}

module.exports = { matchDeltas, expectedShare, SCALE, GAIN_SCALE, LOSS_SCALE };
