import React, { useEffect, useRef } from 'react';
import './HelpDialog.css';

/**
 * Окно с правилами. Открывается кнопкой «Правила» рядом с «Тема».
 *
 * Правила нужны не один раз: их открывают и новички, и те, кто забыл,
 * чем грозит цепочка. Поэтому текста здесь много, а окно прокручивается,
 * а не растягивает страницу.
 */
const HelpDialog: React.FC<{ onClose: () => void }> = ({ onClose }) => {
    const bodyRef = useRef<HTMLDivElement>(null);

    // Пробел и Escape закрывают окно - так привычнее, чем искать кнопку
    useEffect(() => {
        const onKey = (e: KeyboardEvent) => {
            if (e.key === 'Escape') onClose();
        };
        window.addEventListener('keydown', onKey);
        return () => window.removeEventListener('keydown', onKey);
    }, [onClose]);

    // Прокрутка начинается сверху: правила читают с начала, а не с середины
    useEffect(() => {
        if (bodyRef.current) bodyRef.current.scrollTop = 0;
    }, []);

    return (
        <div className="help-overlay" onClick={onClose}>
            <div className="help" onClick={e => e.stopPropagation()} role="dialog"
                aria-label="Правила игры">
                <div className="help-head">
                    <span className="help-title">Точки и квадраты — как играть</span>
                    <button className="help-close" onClick={onClose} title="Закрыть">
                        ✕
                    </button>
                </div>

                <div className="help-body" ref={bodyRef}>
                    <Section title="Цель">
                        <p>
                            На поле 25 точек. Между соседними точками проводятся
                            линии, и каждый квадрат между четырьмя линиями нужно
                            закрыть первым. Всего квадратов 16, и кто закрыл
                            больше — тот выиграл.
                        </p>
                        <p>
                            Партия занимает около трёх минут: линий всего 40, а на
                            ход даётся 15 секунд.
                        </p>
                    </Section>

                    <Section title="Ход">
                        <p>
                            Кликните по линии между двумя точками — она
                            становится вашей. Ходить можно только когда
                            горит надпись «Ваш ход».
                        </p>
                        <p className="help-hint">
                            Первый ход достаётся случайно. Он чуть сильнее, и
                            отметка «1» в табло нужна, чтобы проигрыш не
                            выглядел ошибкой.
                        </p>
                    </Section>

                    <Section title="Главное правило: закрыл квадрат — ходишь ещё раз">
                        <p>
                            Если ваш ход закрыл квадрат, вы забираете его и
                            ходите снова. Это правило продолжения, и именно оно
                            решает почти всю партию.
                        </p>
                        <p>
                            Обратная сторона: если вы закрыли квадрат, то
                            следующий ход можете сделать не сразу, а когда
                            захотите. Поэтому иногда выгодно <b>не закрывать</b>{' '}
                            квадрат, а ходить дальше.
                        </p>
                    </Section>

                    <Section title="Цепочки и красная область">
                        <p>
                            Квадрат с тремя проведёнными сторонами обречён: его
                            заберёт тот, кто проведёт четвёртую. Если такие
                            квадраты идут подряд, начинается <b>цепочка</b>, и
                            соперник забирает её целиком.
                        </p>
                        <p>
                            Красная пунктирная область — это квадраты, которые
                            обязан отдать именно тот, чей сейчас ход. Внизу под
                            полем написано, сколько их. Играйте их ход, пока
                            красная область не мешает.
                        </p>
                        <p className="help-hint">
                            Первые партии лучше доигрывать до конца: цепочки
                            появляются ближе к финалу, и к тому моменту правило
                            уже понятно на практике.
                        </p>
                    </Section>

                    <Section title="Кто ходит и что показывает табло">
                        <p>
                            В табло видно, сколько квадратов собрал каждый, и
                            сколько осталось всего. Счётчик ходов помогает
                            понять, что финал близко.
                        </p>
                        <p>
                            Линии на поле окрашены в цвета игроков. Легенда под
                            полем показывает, чей это цвет.
                        </p>
                    </Section>

                    <Section title="Счёт 8:8">
                        <p>
                            Квадратов 16, поэтому делёж 8:8 теоретически
                            возможен. В такой ничьей побеждает тот, кто закрыл
                            последний квадрат.
                        </p>
                    </Section>

                    <Section title="Если не успел за 15 секунд">
                        <p>
                            Ничего страшного не будет: сервер проведёт за вас
                            случайную линию, и партия продолжится. Это не
                            наказание, а страховка от зависшей партии.
                        </p>
                        <p className="help-hint">
                            Если 15 секунд не хватает на размышление, ход
                            можно не спешить: очередь перейдёт дальше, а
                            таймер начнётся заново.
                        </p>
                        <p>
                            А вот обрыв связи — наказуем. Если связь пропала
                            больше чем на 15 секунд, соперник побеждает. Три
                            таких обрыва подряд, и в следующей партии вы
                            проигрываете автоматически.
                        </p>
                    </Section>

                    <Section title="Игра и рейтинг">
                        <p>
                            <b>Играть</b> ищет живого соперника: случайным
                            игрокам уходит вызов, у каждого 10 секунд на
                            ответ. Не ответил — вызов уходит следующему.
                        </p>
                        <p>
                            <b>Бот</b> доступен всегда и рейтинг не двигает ни
                            в какую сторону — это тренировка.
                        </p>
                        <p>
                            Рейтинговая игра и вызовы друзьям открываются после
                            трёх партий. Считаются все партии, не только игры с
                            ботом. Один раз открыли — больше не закрывается.
                        </p>
                        <p className="help-hint">
                            Во время подбора можно свернуться в бота в любой
                            момент — кнопка «Играть с ботом» есть прямо в панели
                            поиска.
                        </p>
                    </Section>
                </div>
            </div>
        </div>
    );
};

const Section: React.FC<{ title: string; children?: React.ReactNode }> = ({
    title,
    children
}) => (
    <section className="help-section">
        <h3 className="help-section-title">{title}</h3>
        {children}
    </section>
);

export default HelpDialog;
